// Each lesson has two valid opening replies and two endings on each branch.
function makeStory({ opening, branches, ...metadata }) {
  const [context, line, retry] = opening;
  const scenes = { start: { context, line, choices: [] } };
  for (const [key, entry, branch] of branches) {
    const [branchContext, branchLine, endings] = branch;
    scenes.start.choices.push([...entry.slice(0, 2), key, entry[2]]);
    scenes[key] = { context: branchContext, line: branchLine, choices: [] };
    for (const [endingKey, reply, end, endingLine] of endings) {
      scenes[key].choices.push([...reply.slice(0, 2), endingKey, reply[2]]);
      scenes[endingKey] = { line: endingLine, end };
    }
  }
  scenes.start.choices.splice(1, 0, [retry[0], retry[1], null, retry[2]]);
  return { ...metadata, scenes };
}

